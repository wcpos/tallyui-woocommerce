import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { afterEach, expect, test } from 'vitest';
import { wooCountryName, wooStateName } from '../lib/settings/woo-regions';

const script = resolve(__dirname, '../scripts/gen-woo-regions.mjs');
const dirs: string[] = [];
afterEach(() => { for (const dir of dirs.splice(0)) rmSync(dir, { recursive: true, force: true }); });

test('wooCountryName answers WooCommerce\'s name, and undefined rather than the code when it has none', () => {
  expect(wooCountryName('US')).toBe('United States (US)');
  expect(wooCountryName('AU')).toBe('Australia');
  expect(wooCountryName('CW')).toBe('Curaçao');
  expect(wooCountryName('ZZ')).toBeUndefined();
  expect(wooCountryName(undefined)).toBeUndefined();
});

test('wooStateName names the state, and falls back to the stored code', () => {
  expect(wooStateName('US', 'CA')).toBe('California');
  expect(wooStateName('AU', 'NSW')).toBe('New South Wales');
  expect(wooStateName('US', 'XX')).toBe('XX');
  expect(wooStateName('ZZ', 'CA')).toBe('CA');
  expect(wooStateName('US', undefined)).toBeUndefined();
  expect(wooStateName('US', '')).toBeUndefined();
});

function generate(countries: unknown) {
  const dir = mkdtempSync(join(tmpdir(), 'woo-regions-'));
  dirs.push(dir);
  const input = join(dir, 'countries.json');
  const output = join(dir, 'woo-regions.ts');
  writeFileSync(input, JSON.stringify(countries));
  execFileSync(process.execPath, [script, input, output], { stdio: 'pipe' });
  return readFileSync(output, 'utf8');
}

test('the generator decodes entities, leaves a bare &, and drops _links', () => {
  const text = generate([
    { code: 'CW', name: 'Cura&ccedil;ao', states: [], _links: { self: [{ href: 'https://shop.example/' }] } },
    { code: 'CO', name: 'Colombia', states: [{ code: 'SAP', name: 'San Andr&#233;s & Providencia' }, { code: 'X', name: '&#x41;mp &amp; co' }] },
  ]);
  expect(text.split('\n')[0]).toBe('// Generated by apps/pos/scripts/gen-woo-regions.mjs from WCPOS v2\'s countries.json (WooCommerce wc/v3/data/countries). Do not edit.');
  expect(text).toContain('  "CW": ["Curaçao",{}],\n  "CO": ["Colombia",{"SAP":"San Andrés & Providencia","X":"Amp & co"}],\n};');
  expect(text).not.toContain('_links');
  expect(text).not.toContain('shop.example');
});

test('the generator exits non-zero on a named entity it does not know', () => {
  expect(() => generate([{ code: 'XX', name: 'Bad &bogus; name', states: [] }])).toThrow(/bogus/);
});
