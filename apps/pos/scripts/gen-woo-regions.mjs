// Writes apps/pos/lib/settings/woo-regions.ts: WooCommerce's country and state names, keyed by code, with the two
// lookups Settings › General uses. The input is WCPOS v2's packages/core/src/contexts/countries/countries.json, the
// response of WooCommerce's wc/v3/data/countries. HTML entities in names are decoded here, once, as v2 does at render
// time with html-entities. Usage:
//   node apps/pos/scripts/gen-woo-regions.mjs <countries.json> [output, default apps/pos/lib/settings/woo-regions.ts]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// Every named entity v2's countries.json uses (a scan for &name; finds these four), plus amp.
const NAMED = { amp: '&', atilde: 'ã', ccedil: 'ç', eacute: 'é', iacute: 'í' };

const [input, output = fileURLToPath(new URL('../lib/settings/woo-regions.ts', import.meta.url))] = process.argv.slice(2);
if (!input) throw new Error('usage: node apps/pos/scripts/gen-woo-regions.mjs <countries.json> [output]');

/** Decodes &#NNN;, &#xHH; and the named entities in NAMED; a bare & is left as is. */
function decode(text) {
  return text.replace(/&(#\d+|#[xX][0-9a-fA-F]+|[A-Za-z][A-Za-z0-9]*);/g, (_, body) => {
    if (body[0] === '#') return String.fromCodePoint(body[1] === 'x' || body[1] === 'X' ? parseInt(body.slice(2), 16) : Number(body.slice(1)));
    // An entity missing from NAMED stops the run (exit 1), naming it.
    if (!Object.hasOwn(NAMED, body)) throw new Error(`unknown named entity &${body}; in "${text}"`);
    return NAMED[body];
  });
}

const countries = JSON.parse(readFileSync(input, 'utf8'));
const entries = countries.map(({ code, name, states }) =>
  `  ${JSON.stringify(code)}: ${JSON.stringify([decode(name), Object.fromEntries(states.map(s => [s.code, decode(s.name)]))])},`);

const module = `// Generated by apps/pos/scripts/gen-woo-regions.mjs from WCPOS v2's countries.json (WooCommerce wc/v3/data/countries). Do not edit.
export const WOO_REGIONS: Record<string, readonly [name: string, states: Record<string, string>]> = {
${entries.join('\n')}
};

const has = (record: object, key: string) => Object.prototype.hasOwnProperty.call(record, key);

/** v2 general.tsx:247-265: the store's country as WooCommerce names it; undefined (not the code) when unknown. */
export function wooCountryName(code: string | undefined): string | undefined {
  return code && has(WOO_REGIONS, code) ? WOO_REGIONS[code]![0] : undefined;
}

/** v2 general.tsx:247-265: the state's name, else the stored state code; undefined when there is no state. */
export function wooStateName(country: string | undefined, state: string | undefined): string | undefined {
  if (!state) return undefined;
  const states = country && has(WOO_REGIONS, country) ? WOO_REGIONS[country]![1] : undefined;
  return states && has(states, state) ? states[state] : state;
}
`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, module);
